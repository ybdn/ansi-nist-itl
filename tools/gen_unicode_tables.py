#!/usr/bin/env python3
"""Generate src/py/unicode_tables.rs from CPython 3.12 (SPEC §3.6).

The tables mirror the Unicode database compiled into CPython 3.12, which is
what `nistitl` sees at run time: `str.isspace`, `str.isprintable` and the
decimal digits (category Nd) accepted by `int()`.

Usage (from the repository root):

    python3.12 tools/gen_unicode_tables.py > src/py/unicode_tables.rs
"""

import sys
import unicodedata

if sys.version_info[:2] != (3, 12):
    sys.exit("CPython 3.12 is required (found %s)" % sys.version.split()[0])


def ranges(pred):
    """Inclusive ranges of code points satisfying pred, in increasing order."""
    out = []
    start = None
    for c in range(sys.maxunicode + 2):
        ok = c <= sys.maxunicode and pred(chr(c))
        if ok and start is None:
            start = c
        elif not ok and start is not None:
            out.append((start, c - 1))
            start = None
    return out


def decimal_ranges():
    """Ranges of decimal digits, split so that each one maps start..=end to 0..=n."""
    out = []
    for lo, hi in ranges(str.isdecimal):
        start = lo
        for c in range(lo, hi + 1):
            if int(chr(c)) == 0 and c != start:
                out.append((start, c - 1))
                start = c
        out.append((start, hi))
    for lo, hi in out:
        for c in range(lo, hi + 1):
            assert int(chr(c)) == c - lo, hex(c)
    return out


def emit(name, doc, table):
    print()
    print("/// %s" % doc)
    print("pub(crate) const %s: &[(u32, u32)] = &[" % name)
    for lo, hi in table:
        print("    (0x%04X, 0x%04X)," % (lo, hi))
    print("];")


print("//! Unicode tables of CPython %s (Unicode %s)." % (sys.version.split()[0], unicodedata.unidata_version))
print("//!")
print("//! Generated by `tools/gen_unicode_tables.py`: do not edit by hand.")
emit("SPACE", "Inclusive ranges of code points for which `str.isspace()` is true.", ranges(str.isspace))
emit("PRINTABLE", "Inclusive ranges of code points for which `str.isprintable()` is true.", ranges(str.isprintable))
emit(
    "DECIMAL",
    "Inclusive ranges of decimal digits (`str.isdecimal()`); `start` has the value 0, `start + k` the value `k`.",
    decimal_ranges(),
)
