#!/usr/bin/env python3
"""Generate src/alias/names.rs: one constant per distinct alias of
nistitl.ALIASES (SPEC §14.1, LIB-07), in order of first appearance.

Usage (from the repository root, with nistitl 0.6 importable):

    python3.12 tools/gen_alias_names.py > src/alias/names.rs
    cargo fmt
"""

import sys

import nistitl

if getattr(nistitl, "__version__", None) != "0.6":
    sys.exit("nistitl 0.6 is required")

# Aliases that are not Rust identifiers.
IDENTS = {"3DF": "THREE_DF"}


def ranges(types):
    """`[1, 2, 9, 10, 11]` -> `1, 2, 9–11`."""
    out, start, prev = [], None, None
    for t in types + [None]:
        if start is None:
            start = prev = t
        elif t == prev + 1:
            prev = t
        else:
            out.append(str(start) if start == prev else "%d–%d" % (start, prev) if prev > start + 1
                       else "%d, %d" % (start, prev))
            start = prev = t
    return ", ".join(out)


uses = {}
for record_type, table in nistitl.ALIASES.items():
    for tag, alias in table.items():
        uses.setdefault(alias, {}).setdefault(tag, []).append(record_type)

print("//! Alias names of `nistitl` 0.6, one constant per distinct alias.")
print("//!")
print("//! Generated by `tools/gen_alias_names.py`: do not edit by hand.")
print()
for alias, tags in uses.items():
    ident = IDENTS.get(alias, alias)
    assert ident.isidentifier() and ident.isupper() or ident == ident.upper(), alias
    where = "; ".join("tag %d of type%s %s" % (tag, "s" if len(types) > 1 else "", ranges(types))
                      for tag, types in tags.items())
    print("/// `%s`: %s." % (alias, where))
    print('pub const %s: &str = "%s";' % (ident, alias))
print()
print("/// All the constants above, in order.")
print("#[cfg(test)]")
print("pub(crate) const NAMES: &[&str] = &[%s];" % ", ".join(IDENTS.get(a, a) for a in uses))
