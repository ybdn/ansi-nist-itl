#!/usr/bin/env python3
"""Generate src/alias/table.rs from nistitl.ALIASES (SPEC §4.5, annex A).

The order of the types and, within a type, of the tags is the order of the
Python dict, which `nistitl` relies on to find "the first tag whose alias is X".

Usage (from the repository root, with nistitl 0.6 importable):

    python3.12 tools/gen_aliases.py > src/alias/table.rs
"""

import sys

import nistitl

if getattr(nistitl, "__version__", None) != "0.6":
    sys.exit("nistitl 0.6 is required")

print("//! `ALIASES` of `nistitl` 0.6, in table order.")
print("//!")
print("//! Generated by `tools/gen_aliases.py`: do not edit by hand.")
print()
print("/// `(record type, [(tag, alias)])`, in the order of `nistitl.ALIASES`.")
print("pub(crate) const ALIASES: &[(u32, &[(u32, &str)])] = &[")
for record_type, table in nistitl.ALIASES.items():
    print("    (")
    print("        %d," % record_type)
    print("        &[")
    for tag, alias in table.items():
        assert isinstance(tag, int) and isinstance(alias, str) and alias.isascii()
        print('            (%d, "%s"),' % (tag, alias))
    print("        ],")
    print("    ),")
print("];")
